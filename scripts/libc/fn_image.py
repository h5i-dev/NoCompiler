#!/usr/bin/env python3
"""Emit a Lean module holding one function's instruction words, as `Chunk`s at its address.

    fn_image.py ELF FUNCTION NAMESPACE [--chunk N] [--struct EXPORTED.lean]

With --struct, the function's `Struct.Func` (its blocks and loops, as `nocompiler export` gave them in
EXPORTED.lean, `FUNCTION_func`) is copied as `func`, for proofs by `nocompiler_auto`.

The module defines `base`, `size` (bytes), `chunks`, `img : Code := Code.ofChunks base chunks` and
`dom : Dom := [(base, size)]`, plus `elfSha256` and `fnSha256` (the function's bytes). A library proof made over
`img` holds in any image with the same words on `dom` (VerifiedProc.of_code_eq), and, for pcFree code, at any
other base (VerifiedProc.shift).
"""
import hashlib
import subprocess
import sys


def load(path):
    data = open(path, 'rb').read()
    ph = subprocess.run(['readelf', '-lW', path], capture_output=True, text=True, check=True).stdout
    loads = []
    for line in ph.splitlines():
        p = line.split()
        if p and p[0] == 'LOAD':
            loads.append((int(p[2], 16), int(p[1], 16), int(p[4], 16)))
    return data, loads


def func(path, name):
    out = subprocess.run(['nm', '-S', '--defined-only', path], capture_output=True, text=True, check=True).stdout
    addrs = set()
    nosize = None
    for line in out.splitlines():
        p = line.split()
        # Assembler-local labels (.Lpcrel_hi*, ...) and mapping symbols ($x) are not functions: as the
        # next symbol they would cut a function without .size at an auipc's label (crt1's _start).
        if p and (p[-1].startswith('.L') or p[-1].startswith('$')):
            continue
        if len(p) == 4 and p[2] in 'Tt':
            addrs.add(int(p[0], 16))
            if p[3] == name:
                return int(p[0], 16), int(p[1], 16)
        elif len(p) == 3 and p[1] in 'Tt':
            addrs.add(int(p[0], 16))
            if p[2] == name:
                nosize = int(p[0], 16)
    if nosize is not None:
        # Assembly without `.size` (musl's __set_thread_area, crt1's _start): up to the next symbol, as the
        # loader (crates/nocompiler/src/elf.rs) and scripts/libc/reach.py size it.
        later = sorted(a for a in addrs if a > nosize)
        if later:
            return nosize, later[0] - nosize
    sys.exit(f'{name}: not a function of {path}')


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    chunk = 1 << 30
    struct = None
    if '--struct' in sys.argv:
        sp = sys.argv[sys.argv.index('--struct') + 1]
        args.remove(sp)
        struct = sp
    if '--chunk' in sys.argv:
        chunk = int(sys.argv[sys.argv.index('--chunk') + 1])
        args.remove(str(chunk))
    path, names_arg, ns = args
    names = names_arg.split(',')
    data, loads = load(path)
    fns = []
    for name in names:
        va, size = func(path, name)
        if size % 4:
            sys.exit(f'{name}: size {size} not a multiple of 4')
        for lva, off, fsz in loads:
            if lva <= va < lva + fsz:
                fns.append((va, size, name, data[off + va - lva: off + va - lva + size]))
                break
        else:
            sys.exit(f'{name}: not in a LOAD segment')
    fns.sort()
    structs = {}
    if struct:
        for line in open(struct):
            for _, _, name, _ in fns:
                if line.startswith(f'def {name}_func : Struct.Func := ') or \
                        line.startswith(f'def {name}_labels : List (String × Word) := '):
                    structs[name] = (structs.get(name, '') + '\n' + line.rstrip()).strip()
        for _, _, name, _ in fns:
            if name not in structs:
                sys.exit(f'{name}_func: not in {struct}')
    single = len(fns) == 1
    va0 = fns[0][0]
    total = (fns[-1][0] + fns[-1][1] - va0) // 4
    elf = path.split("/")[-1]
    out = [
        '/-',
        f'Generated by scripts/libc/fn_image.py; do not edit.',
        f'Source: {elf}, function{"" if single else "s"} {", ".join(f"`{n}`" for _, _, n, _ in fns)}.',
        f'SHA-256 of the ELF: {hashlib.sha256(data).hexdigest()}',
        '-/',
        'import Examples.Libc.Musl.Base',
        '',
        f'set_option maxRecDepth {max(2000, 8 * total)}',
        '',
        f'namespace {ns}',
        'open NoCompiler',
        '',
    ]
    for va, size, name, b in fns:
        tag = 'fnSha256' if single else f'{name}_sha256'
        out.append(f'/-- SHA-256 of `{name}`\'s {size} bytes. -/')
        out.append(f'def {tag} : String := "{hashlib.sha256(b).hexdigest()}"')
    out += [f'def elfSha256 : String := "{hashlib.sha256(data).hexdigest()}"', '']
    cnames = []
    pos = 0  # words from va0
    def emit(o, n, bits, what):
        i = len(cnames)
        out.append(f'/-- {what} -/')
        out.append(f'def chunk_{i} : Chunk := ⟨{o}, {n}, 0x{bits:x}⟩')
        cnames.append(f'chunk_{i}')
    for va, size, name, b in fns:
        o = (va - va0) // 4
        if o > pos:
            emit(pos, o - pos, 0, 'Filler (no instruction) between the functions.')
        words = size // 4
        for c0 in range(0, words, chunk):
            n = min(chunk, words - c0)
            emit(o + c0, n, int.from_bytes(b[4 * c0: 4 * (c0 + n)], 'little'), f'`{name}`.')
        pos = o + words
    out += [
        f'/-- The chunks, in order. -/',
        f'def chunks : List Chunk := [{", ".join(cnames)}]',
    ]
    if single:
        va, size, name, _ = fns[0]
        out += [
            f'/-- `{name}`\'s address in {elf}. -/',
            f'def base : Word := 0x{va:x}#64',
            f'def size : Nat := {size}',
            f'def img : Code := Code.ofChunks 0x{va:x}#64 chunks',
            f'def dom : Dom := [(base, size)]',
        ]
    else:
        for va, size, name, _ in fns:
            out.append(f'def {name}_entry : Word := 0x{va:x}#64')
        out += [
            f'def base : Word := 0x{va0:x}#64',
            f'def img : Code := Code.ofChunks 0x{va0:x}#64 chunks',
            f'/-- The functions\' bytes (not the fillers). -/',
            f'def dom : Dom := [{", ".join(f"(0x{va:x}#64, {size})" for va, size, _, _ in fns)}]',
        ]
    out += [
        f'theorem chunks_contig : Chunk.contig 0 chunks = true := by decide +kernel',
        f'theorem chunks_bound : 4 * Chunk.total chunks < 2 ^ 64 := by decide +kernel',
    ]
    for _, _, name, _ in fns:
        if name in structs:
            out += [f'/-- `{name}`\'s blocks, loops and labels (`nocompiler export`). -/', structs[name]]
    out += ['', f'end {ns}', '']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
