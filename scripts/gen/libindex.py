#!/usr/bin/env python3
"""Index of the generic library lean/NoCompiler/Lib (round 7): per module, its header's first
paragraph, then each theorem/definition with its docstring. Writes Markdown.

usage: libindex.py [LIB_DIR] > docs/toolkit/library.md
       libindex.py --check [LIB_DIR]   (exit 1 when docs/toolkit/library.md is not what it would write)
"""
import os, re, sys

# A declaration at the start of a line, after an optional attribute; `private` ones are skipped.
DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(private\s+)?(theorem|def)\s+(\S+)", re.M)
# A docstring that ends right before a declaration (only whitespace between).
DOC = re.compile(r"/--((?:(?!-/).)*)-/\s*$", re.S)


def one_line(doc):
    return " ".join(doc.split())


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    lib = args[0] if args else "lean/NoCompiler/Lib"
    if "--check" in sys.argv:
        import contextlib, io
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            index(lib)
        doc = os.path.join(os.path.dirname(os.path.abspath(lib)), "..", "..", "docs/toolkit/library.md")
        if open(os.path.normpath(doc)).read() != buf.getvalue():
            print("docs/toolkit/library.md is stale: run scripts/gen/libindex.py > docs/toolkit/library.md")
            sys.exit(1)
        print("docs/toolkit/library.md is current")
        return
    index(lib)


def index(lib):
    files = sorted(f for f in os.listdir(lib) if f.endswith(".lean"))
    print("# The generic library: `lean/NoCompiler/Lib`\n")
    print("Generated by `scripts/gen/libindex.py`; do not edit by hand. Every name is in namespace")
    print("`NoCompiler.Lib` unless written with its namespace (`Region.`, `Perm.`); `import NoCompiler`")
    print("brings all of it.\n")
    n = 0
    for f in files:
        s = open(os.path.join(lib, f)).read()
        hdr = re.search(r"/-!\s*\n#[^\n]*\n\n(.*?)(?:\n\n|-/)", s, re.S)
        print(f"## {f[:-5]}\n")
        if hdr:
            print(" ".join(hdr.group(1).split()) + "\n")
        for m in DECL.finditer(s):
            if m.group(1) or m.group(3).startswith("_"):
                continue
            d = DOC.search(s, max(0, m.start() - 2000), m.start())
            doc = one_line(d.group(1)) if d else ""
            print(f"- `{m.group(3)}`" + (f": {doc}" if doc else ""))
            n += 1
        print()
    print(f"{n} items in {len(files)} modules.")


if __name__ == "__main__":
    main()
