#!/usr/bin/env python3
"""elf_snapshot_lean: LPS's elf-snapshot (tools/elf_snapshot.py at f1006fe8, MIT, Theorem Labs) with a Lean
emitter.

The ELF is parsed by LPS's own `_parse_elf` (loaded from the LPS git repository at the pinned commit, not
copied), so the segments, page-rounded extents, file-page slack, bss zero fill, permissions, entry point and
program-header info are exactly what elf_snapshot gives oss-verify's Rocq images. Only the output differs:
a Lean module (LPS/MemImageType.lean's `Segment`, `PhdrInfo`, `MemImage`) instead of a .v plus .hex files;
each segment's bytes are the same hex chunks (`_hex_chunks`) as String literals.

usage: elf_snapshot_lean.py ELF MODULE_NAME OUT.lean [--lps-repo DIR] [--commit SHA]
"""
import argparse, hashlib, subprocess, sys, types

DEFAULT_REPO = "/mnt/scratch/ec2-user/prior-art/lps"
DEFAULT_COMMIT = "f1006fe8178338a499b5e5c41be83006c4edd058"


def load_elf_snapshot(repo, commit):
    src = subprocess.run(["git", "-C", repo, "show", f"{commit}:tools/elf_snapshot.py"],
                         check=True, capture_output=True, text=True).stdout
    mod = types.ModuleType("lps_elf_snapshot")
    mod.__file__ = f"{repo}/tools/elf_snapshot.py@{commit}"
    exec(compile(src, mod.__file__, "exec"), mod.__dict__)
    return mod, hashlib.sha256(src.encode()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("elf"); ap.add_argument("module"); ap.add_argument("out")
    ap.add_argument("--lps-repo", default=DEFAULT_REPO); ap.add_argument("--commit", default=DEFAULT_COMMIT)
    ap.add_argument("--max-chunk-bytes", type=int, default=None,
                    help="LPS's MAX_CHUNK_BYTES (default LPS's, ~8 MB, for Rocq's O(1) PrimString); smaller chunks make the "
                         "same bytes cheap for Lean's kernel, whose String access is linear in the string")
    ap.add_argument("--hex-form", action="store_true",
                    help="emit each segment as LPS.Bridge.SegH (its bytes as one number N, the hex chunk being "
                         "hexStr N k): the same Segment values, readable by Lean's kernel (LPS/Bridge/HexImage.lean)")
    a = ap.parse_args()
    es, src_sha = load_elf_snapshot(a.lps_repo, a.commit)
    if a.max_chunk_bytes: es.MAX_CHUNK_BYTES = a.max_chunk_bytes
    elf = es._parse_elf(a.elf)
    elf_sha = hashlib.sha256(open(a.elf, "rb").read()).hexdigest()
    ns = f"LPS.Images.{a.module}"
    L = ["import LPS.Bridge.HexImage" if a.hex_form else "import LPS.LinuxProcessSem.MemImageType", "",
         "/-!", f"# Memory image of `{a.elf.split('/')[-1]}` (generated; do not edit)", "",
         f"ELF sha256 {elf_sha}. Generated by scripts/lps/elf_snapshot_lean.py from LPS tools/elf_snapshot.py at",
         f"{a.commit} (MIT, Theorem Labs; source sha256 {src_sha}): its `_parse_elf` and `_hex_chunks`, unchanged" +
         (f" (MAX_CHUNK_BYTES = {a.max_chunk_bytes})." if a.max_chunk_bytes else "."),
         "-/", "", f"namespace {ns}", "open LPS", ""]
    names = []
    if a.hex_form:
        hs = []
        for i, seg in enumerate(elf["segments"]):
            chunks = es._hex_chunks(seg["hex_bytes"])
            # LPS's tool writes this segment as one chunk (under its cap); hexStr N k is that chunk
            assert len(chunks) == 1 and chunks[0] == seg["hex_bytes"], "segment over LPS's chunk cap"
            bs = bytes.fromhex(seg["hex_bytes"])
            assert bs.hex() == seg["hex_bytes"]          # lowercase, two digits a byte: hexStr's format
            N = int.from_bytes(bs, "little")
            L.append(f"def segH_{i:03d} : LPS.Bridge.SegH :=")
            L.append(f'  ⟨0x{seg["base"]:x}, 0x{seg["size"]:x}, "{seg["perms"]}", 0x{N:x}, {len(bs)}⟩')
            hs.append(f"segH_{i:03d}")
        L.append(f"def segs_h : List LPS.Bridge.SegH := [{', '.join(hs)}]")
        L.append("def loaded_segments : List Segment := segs_h.map LPS.Bridge.SegH.toSeg")
        elf_segments = []
    else:
        elf_segments = elf["segments"]
    for i, seg in enumerate(elf_segments):
        chunks = es._hex_chunks(seg["hex_bytes"])
        cn = []
        for j, ch in enumerate(chunks):
            n = f"seg_bytes_{i:03d}" if len(chunks) == 1 else f"seg_bytes_{i:03d}_{j:03d}"
            cn.append(n)
            L.append(f'def {n} : String := "{ch}"')
        L.append(f"def segment_{i:03d} : Segment :=")
        L.append(f'  {{ seg_base := 0x{seg["base"]:x}, seg_size := 0x{seg["size"]:x}, seg_perms := "{seg["perms"]}",')
        L.append(f"    seg_bytes := [{', '.join(cn)}] }}")
        names.append(f"segment_{i:03d}")
        L.append("")
    if not a.hex_form:
        L.append(f"def loaded_segments : List Segment := [{', '.join(names)}]")
    L.append(f"def init_pc : Nat := 0x{elf['entry']:x}")
    p = elf["phdrs"]
    L.append(f"def phdrs : PhdrInfo := {{ ph_addr := 0x{p['addr']:x}, ph_ent := {p['ent']}, ph_num := {p['num']} }}")
    L.append("def image : MemImage := ⟨loaded_segments, init_pc, phdrs⟩")
    L += ["", f"end {ns}", ""]
    open(a.out, "w").write("\n".join(L))
    tot = sum(len(s["hex_bytes"]) // 2 for s in elf["segments"])
    print(f"{a.out}: {len(elf['segments'])} segments, {tot} bytes, entry 0x{elf['entry']:x}, phdrs {p}")


if __name__ == "__main__":
    main()
