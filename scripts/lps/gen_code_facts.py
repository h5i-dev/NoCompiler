#!/usr/bin/env python3
"""Generate the per-image facts the LPS bridge's step theorems take, as kernel-checked theorems.

Input: a NoCompiler export module (`nocompiler export`: `.text` as chunks, `code := Code.ofChunks BASE chunks`,
`chunks_contig`) and an LPS image module generated with `scripts/lps/elf_snapshot_lean.py --hex-form` (its
segments as `SegH`s). Output: a Lean module proving `<name>_code_facts`: every word the export's `code` fetches
is fetched by LPS from the image, and the two decoders agree on it (LPS/Bridge/Chunks.lean,
`codeFacts_ofChunks`). One `decide +kernel` theorem per chunk; chunks longer than STEP words are checked in
ranges of STEP (LPS/Bridge/HexImage.lean, `codeAgreeH_of_ranges`): the kernel's cache is per declaration, and
one declaration over all of fuzz_qdisc's 8961 words runs out of memory.

usage: gen_code_facts.py EXPORT.lean EXPORT_MODULE IMAGE_MODULE OUT.lean NAME [--step 128]
(the modules by their Lean names, e.g. Examples.QdiscD.ArtImg Examples.LPS.Images.QdiscPlainE5rH)
"""
import argparse, re


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("export"); ap.add_argument("export_module"); ap.add_argument("image_module")
    ap.add_argument("out"); ap.add_argument("name"); ap.add_argument("--step", type=int, default=128)
    a = ap.parse_args()
    src = open(a.export).read()
    ns = re.search(r"^namespace (\S+)", src, re.M).group(1)
    base = re.search(r"^def code : Code := Code\.ofChunks (\S+) chunks", src, re.M).group(1)
    lens = [int(m.group(2)) for m in re.finditer(r"^def chunk_(\d+) : Chunk := ⟨\d+, (\d+),", src, re.M)]
    assert re.search(r"^theorem chunks_contig", src, re.M), "export has no chunks_contig"
    step = a.step
    L = [f"import {a.image_module}", "import LPS.Bridge.Chunks", f"import {a.export_module}", "",
         "/-! Generated by scripts/lps/gen_code_facts.py; do not edit. -/", "",
         "set_option maxRecDepth 100000",
         f"open LPS LPS.Bridge LPS.RiscvSemantics {a.image_module} {ns}", "",
         f"namespace {a.name}", "",
         "theorem hok : ∀ h ∈ segs_h, h.ok := by decide"]
    for i, n in enumerate(lens):
        c = f"(chunk_{i}.code {base})"
        if n <= step:
            L.append(f"theorem r{i} : codeAgreeH segs_h {c} = true := by decide +kernel")
            continue
        m = (n + step - 1) // step
        for j in range(m):
            L.append(f"theorem r{i}_{j} : agreeRangeH segs_h {c} {step * j} {step} = true := by decide +kernel")
        L.append(f"theorem r{i} : codeAgreeH segs_h {c} = true :=")
        L.append(f"  codeAgreeH_of_ranges (step := {step}) (m := {m}) (by decide) fun j hj => by")
        L.append("    match j, hj with")
        L += [f"    | {j}, _ => exact r{i}_{j}" for j in range(m)]
        L.append(f"    | _ + {m}, hj => omega")
    L.append(f"theorem allH : chunks.all (fun c => codeAgreeH segs_h (c.code {base})) = true := by")
    L.append("  simp only [chunks, List.all_cons, List.all_nil, Bool.and_true, Bool.and_eq_true]")
    L.append("  exact ⟨" + ", ".join(f"r{i}" for i in range(len(lens))) + "⟩")
    L.append(f"""
/-- Every word the export's `code` fetches: LPS fetches it from the image, and the decoders agree. -/
theorem code_facts {{pc : NoCompiler.Word}} {{w : BitVec 32}} (h : code.fetch pc = some w) :
    fetch_word loaded_segments pc = some w ∧
      ∀ i j, NoCompiler.decode w = some i → toLPS i = some j →
        LPS.decode w = some j ∧ bv_unsigned (bits 0 2 w) = 3 :=
  codeFacts_ofChunks (cs := chunks) chunks_contig (by decide)
    (fun c hc => by
      rw [show loaded_segments = segs_h.map SegH.toSeg from rfl, codeAgree_hex hok]
      exact List.all_eq_true.1 allH c hc) h

end {a.name}
""")
    open(a.out, "w").write("\n".join(L))
    print(f"{a.out}: {len(lens)} chunks, {sum(lens)} words, {sum(1 for n in lens if n > step)} split in ranges of {step}")


if __name__ == "__main__":
    main()
