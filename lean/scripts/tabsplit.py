#!/usr/bin/env python3
"""Write a kernel module proving `tabOk f code args table` one point at a time (one
`decide +kernel` per point, chained by `rangeAll_succ`), so no single kernel check holds
every point's entailments at once.

Usage: tabsplit.py NS FN SIZE IMPORT[,IMPORT...] OPEN [TABLE] > out.lean
       tabsplit.py NS FN SIZE IMPORT[,IMPORT...] OPEN TABLE --chunks N --mod MODULE --dir DIR
  With --chunks, the points go into N modules `MODULE_c<i>` (DIR/<last part>_c<i>.lean), each its
  own Lean process when built (memory is bounded per chunk), and DIR/<last part>.lean (MODULE)
  imports them and assembles `tab_ok`.
"""
import os
import sys

args = sys.argv[1:]
opts = {}
for flag in ("--chunks", "--mod", "--dir"):
    if flag in args:
        i = args.index(flag)
        opts[flag] = args[i + 1]
        del args[i:i + 2]
ns, fn, size, imps, extra = args[0], args[1], int(args[2]), args[3].split(","), args[4]
tab = args[5] if len(args) > 5 else "table"
P = f"pointOk {fn} code args {tab}"
opens = f"open NoCompiler NoCompiler.Typed NoCompiler.Typed.Track {extra}"


def header(imports, doc):
    return [f"import {i}" for i in imports] + ["", f"/-! {doc} -/", f"namespace {ns}", opens, ""]


def tail_lines():
    out = ["", f"theorem upto_0 : (List.range 0).all ({P}) = true := rangeAll_zero _"]
    for k in range(size):
        out.append(f"theorem upto_{k+1} : (List.range {k+1}).all ({P}) = true := rangeAll_succ upto_{k} pt_{k}")
    out += ["",
            f"theorem tab_ok : tabOk {fn} code args {tab} = true :=",
            f"  tabOk_of_parts (by decide +kernel) (by rw [show {fn}.size = {size} from rfl]; exact upto_{size})",
            "", f"end {ns}", ""]
    return out


if "--chunks" not in opts:
    out = header(imps, f"The table check of `{fn}`, split per point (generated by\n    lean/scripts/tabsplit.py; heavy: build alone).")
    for k in range(size):
        out.append(f"theorem pt_{k} : {P} {k} = true := by decide +kernel")
    print("\n".join(out + tail_lines()))
else:
    n = int(opts["--chunks"])
    mod, d = opts["--mod"], opts["--dir"]
    base = mod.split(".")[-1]
    step = (size + n - 1) // n
    chunks = []
    for c in range(n):
        a, b = c * step, min(size, (c + 1) * step)
        if a >= b:
            break
        cm = f"{mod}_c{c}"
        chunks.append(cm)
        out = header(imps, f"Points {a} … {b - 1} of `{fn}`'s table check (generated by\n    lean/scripts/tabsplit.py; heavy).")
        for k in range(a, b):
            out.append(f"theorem pt_{k} : {P} {k} = true := by decide +kernel")
        out += ["", f"end {ns}", ""]
        open(os.path.join(d, f"{base}_c{c}.lean"), "w").write("\n".join(out))
    out = header(imps + chunks, f"The table check of `{fn}`, from {len(chunks)} chunk modules (generated by\n    lean/scripts/tabsplit.py).")
    open(os.path.join(d, f"{base}.lean"), "w").write("\n".join(out + tail_lines()))
    print(f"wrote {len(chunks)} chunks and {base}.lean")
