#!/usr/bin/env python3
"""Write a kernel module proving `tabOk f code args table` one point at a time (one
`decide +kernel` per point, chained by `rangeAll_succ`), so no single kernel check holds
every point's entailments at once. Usage: tabsplit.py NS FN SIZE IMPORT[,IMPORT...] OPEN [TABLE] > out.lean"""
import sys
ns, fn, size, imps, extra = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4].split(","), sys.argv[5]
tab = sys.argv[6] if len(sys.argv) > 6 else "table"
P = f"pointOk {fn} code args {tab}"
out = [f"import {i}" for i in imps] + ["", f"/-! The table check of `{fn}`, split per point (generated by",
       "    lean/scripts/tabsplit.py; heavy: build alone). -/", f"namespace {ns}",
       f"open NoCompiler NoCompiler.Typed NoCompiler.Typed.Track {extra}", ""]
for k in range(size):
    out.append(f"theorem pt_{k} : {P} {k} = true := by decide +kernel")
out.append("")
out.append(f"theorem upto_0 : (List.range 0).all ({P}) = true := rangeAll_zero _")
for k in range(size):
    out.append(f"theorem upto_{k+1} : (List.range {k+1}).all ({P}) = true := rangeAll_succ upto_{k} pt_{k}")
out += ["",
        f"theorem tab_ok : tabOk {fn} code args {tab} = true :=",
        f"  tabOk_of_parts (by decide +kernel) (by rw [show {fn}.size = {size} from rfl]; exact upto_{size})",
        "", f"end {ns}", ""]
print("\n".join(out))
