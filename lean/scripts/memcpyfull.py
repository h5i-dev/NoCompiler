#!/usr/bin/env python3
"""musl memcpy, fully kernel-checked: a module that discharges both hypotheses of
`memcpy_correct_of` (docs/typed/value-tracker.md).

Input: U's certificate module for memcpy (`certgen.py --split` output; its record part equals
`Examples.Musl.MemcpyRecord`, which this checks). Output: `import Examples.Musl.MemcpyAny`,
`Examples.Musl.MemcpyTabOk`, `NoCompiler.Typed.Sound.TrackCerts`, then U's certificates and
per-point kernel theorems (`fnc_memcpy`, `chk_memcpy`), then

  theorem memcpy_verified (T) : VerifiedImg code ... (signature post ∧ Copied)

from `chk_memcpy` (the type check, certificates) and `tab_ok` (the table check, for
`fn_memcpy`; `tabOk_certs` carries it to `fnc_memcpy`). Heavy (two kernel checks): build alone
under the 8 GB rule. The output is generated; keep it with the kernel modules, outside the repo.

Usage: lean/scripts/memcpyfull.py U_MODULE OUT.lean
"""
import os
import re
import sys

inp, out = sys.argv[1], sys.argv[2]
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rec = open(os.path.join(here, "Examples/Musl/MemcpyRecord.lean"), encoding="utf-8").read()
text = open(inp, encoding="utf-8").read()
m = re.search(r"^(set_option maxHeartbeats 0 in\n)?def certs_memcpy", text, re.M)
if not m:
    sys.exit("no certificates in the input")
base, rest = text[: m.start()], text[m.start():]


def decls(t):
    t = t.split("\n#eval", 1)[0]
    return [l for l in t.splitlines() if l.strip() and not l.startswith("--")]


if decls(base) != decls(rec):
    sys.exit("the input's record differs from Examples/Musl/MemcpyRecord.lean: regenerate one")
rest = re.sub(r"^#print axioms .*$", "", rest, flags=re.M)
rest = rest.replace("\nend NoCompiler.Typed.Export.memcpy", "")
head = """-- Generated by lean/scripts/memcpyfull.py from U's certificate module. Do not edit.
import Examples.Musl.MemcpyAny
import Examples.Musl.MemcpyTabOk
import NoCompiler.Typed.Sound.TrackCerts

namespace NoCompiler.Typed.Export.memcpy
open NoCompiler NoCompiler.Typed

"""
tail = """
set_option maxRecDepth 100000 in
open NoCompiler.Typed.Track NoCompiler.Examples.Musl.MemcpyTable in
/-- **musl memcpy, kernel-checked.** On the linked image, under memcpy's signature, the
    compiled memcpy meets the signature and copies: `d[0, n)` holds the entry bytes of
    `s[0, n)`, every other byte is as on entry. No hypotheses: the type check is `chk_memcpy`
    (certificates), the table check `tab_ok`. -/
theorem memcpy_verified (T : TokEnv) :
    VerifiedImg code [(fnc_memcpy.entry, 4 * fnc_memcpy.size)] fnc_memcpy.entry
      { fnc_memcpy.sig.spec T with
        post := (fun a s s' => (fnc_memcpy.sig.spec T).post a s s' ∧
          Copied s.mem s'.mem (s.reg 10) (s.reg 11) (s.reg 12).toNat) } :=
  NoCompiler.Examples.Musl.Memcpy.memcpy_correct_of fnc_memcpy code T rfl rfl (by decide)
    chk_memcpy
    ((tabOk_certs (f := fn_memcpy) (f' := fnc_memcpy) (c := code) (C := args) (t := tablec)
        (fun k => (certs_memcpy.lookup k).getD (.table [])) rfl rfl rfl rfl).trans
      tab_ok)

#print axioms memcpy_verified

end NoCompiler.Typed.Export.memcpy
"""
open(out, "w", encoding="utf-8").write(head + rest + tail)
print(f"wrote {out} ({len(head + rest + tail)} bytes)")
