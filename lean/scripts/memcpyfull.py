#!/usr/bin/env python3
"""musl memcpy, fully kernel-checked: a module that discharges both hypotheses of
`memcpy_correct_of` (docs/typed/value-tracker.md).

Input: U's certificate module for memcpy (`certgen.py --split` output; its record part equals
`Examples.Musl.MemcpyRecord`, which this checks). Output: `import Examples.Musl.MemcpyAny`,
`Examples.Musl.MemcpyTabOk`, `NoCompiler.Typed.Sound.TrackCerts`, then U's certificates and
per-point kernel theorems (`fnc_memcpy`, `chk_memcpy`), then

  theorem memcpy_verified (T) : VerifiedImg code ... (signature post ∧ Copied)

from `chk_memcpy` (the type check, certificates) and `tab_ok` (the table check, for
`fn_memcpy`; `tabOk_certs` carries it to `fnc_memcpy`). Heavy (two kernel checks): build alone
under the 8 GB rule. The output is generated; keep it with the kernel modules, outside the repo.

Usage: lean/scripts/memcpyfull.py U_MODULE OUT.lean [FN [Module [NS]]]
  FN (default memcpy) names the function: the record `Examples/Musl/<Module>Record.lean`, the
  table module `Examples.Musl.<Module>TabOk`, the theorem file `Examples.Musl.<Module>Any`
  (`<fn>_correct_of`). Module defaults to FN capitalized.
"""
import os
import re
import sys

inp, out = sys.argv[1], sys.argv[2]
fn = sys.argv[3] if len(sys.argv) > 3 else "memcpy"
Mod = sys.argv[4] if len(sys.argv) > 4 else fn.capitalize()
ns = sys.argv[5] if len(sys.argv) > 5 else fn  # the record's namespace (memcpy-x: memcpy_x)
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rec = open(os.path.join(here, f"Examples/Musl/{Mod}Record.lean"), encoding="utf-8").read()
text = open(inp, encoding="utf-8").read()
m = re.search(rf"^(set_option maxHeartbeats 0 in\n)?def certs_{fn}", text, re.M)
if not m:
    sys.exit("no certificates in the input")
base, rest = text[: m.start()], text[m.start():]


def decls(t):
    t = t.split("\n#eval", 1)[0]
    return [l for l in t.splitlines() if l.strip() and not l.startswith("--")]


if decls(base) != decls(rec):
    sys.exit(f"the input's record differs from Examples/Musl/{Mod}Record.lean: regenerate one")
rest = re.sub(r"^#print axioms .*$", "", rest, flags=re.M)
rest = rest.replace(f"\nend NoCompiler.Typed.Export.{ns}", "")
head = f"""-- Generated by lean/scripts/{fn}full.py from U's certificate module. Do not edit.
import Examples.Musl.{Mod}Any
import Examples.Musl.{Mod}TabOk
import NoCompiler.Typed.Sound.TrackCerts

namespace NoCompiler.Typed.Export.{ns}
open NoCompiler NoCompiler.Typed

"""
tail = f"""
set_option maxRecDepth 100000 in
open NoCompiler.Typed.Track NoCompiler.Examples.Musl.{Mod}Table in
/-- **musl {fn}, kernel-checked.** On the linked image, under {fn}'s signature, the
    compiled {fn} meets the signature and copies: `d[0, n)` holds the entry bytes of
    `s[0, n)`, every other byte is as on entry. No hypotheses: the type check is `chk_{fn}`
    (certificates), the table check `tab_ok`. -/
theorem {fn}_verified (T : TokEnv) :
    VerifiedImg code [(fnc_{fn}.entry, 4 * fnc_{fn}.size)] fnc_{fn}.entry
      {{ fnc_{fn}.sig.spec T with
        post := (fun a s s' => (fnc_{fn}.sig.spec T).post a s s' ∧
          Copied s.mem s'.mem (s.reg 10) (s.reg 11) (s.reg 12).toNat) }} :=
  NoCompiler.Examples.Musl.{Mod}.{fn}_correct_of fnc_{fn} code T rfl rfl (by decide)
    chk_{fn}
    ((tabOk_certs (f := fn_{fn}) (f' := fnc_{fn}) (c := code) (C := args) (t := tablec)
        (fun k => (certs_{fn}.lookup k).getD (.table [])) rfl rfl rfl rfl).trans
      tab_ok)

#print axioms {fn}_verified

end NoCompiler.Typed.Export.{ns}
"""
open(out, "w", encoding="utf-8").write(head + rest + tail)
print(f"wrote {out} ({len(head + rest + tail)} bytes)")
