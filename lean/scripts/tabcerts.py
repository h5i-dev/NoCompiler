#!/usr/bin/env python3
"""Certificates for a copy table's kernel check (docs/typed/value-tracker.md).

The tracker's entailments (`pointOk` on each point's type) are new goals, not the checker's,
so the record's certificates do not cover them. This evaluates `pointOk` at every point with
the point's type in `CertMode.log k` (compiled evaluation, `lake lean`), collects the printed
certificates (`certgen.parse_log`), and writes a module with the table plus, per point, a
`CertMode.table` (`Table.certs`), so the kernel only checks certificates. Untrusted hints: a
missing or wrong certificate only makes `tabOk` fail.

Usage: lean/scripts/tabcerts.py TABLE_MODULE NS FN SIZE OUT.lean
  (TABLE_MODULE defines `table`, `args`; e.g. Examples.Musl.MemcpyTable)
"""
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import certgen  # noqa: E402

mod, ns, fn, size, out = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4]), sys.argv[5]
key = fn.removeprefix("fn_")
opens = "open NoCompiler NoCompiler.Typed NoCompiler.Typed.Track"
rec_ns = f"NoCompiler.Typed.Export.{key}"

log = f"""import {mod}
{opens} {rec_ns} {ns}

def tlog : Table := {{ table with certs := (List.range {size}).map (fun k => (k, .log k)) }}
-- behind a runtime value (z = 0), so the compiler cannot hoist a check out of the #eval
#eval show IO Unit from do
  let t ← IO.monoMsNow
  let z := t - t
  IO.println s!"DONE {key} {{(List.range {size}).map (fun k => pointOk {fn} code args tlog (k + z))}}"
"""
with tempfile.NamedTemporaryFile("w", suffix=".lean", delete=False, dir="/tmp") as fh:
    fh.write(log)
    path = fh.name
r = certgen.run_lean(path, int(os.environ.get("LEAN_TIMEOUT", "1800")))
os.unlink(path)
certs, done = certgen.parse_log(r.stdout + r.stderr, [key])
if key not in done:
    sys.exit("log run failed:\n" + (r.stdout + r.stderr)[-3000:])
print("DONE", done[key][:200], file=sys.stderr)
pts = sorted({int(k) for (g, k) in list(certs) + list(certgen.SPLITS) + list(certgen.OKS)
              if g == key and k != "entry"})
lines = [f"-- Generated by lean/scripts/tabcerts.py (untrusted hints; `tabOk` re-checks). Do not edit.",
         f"import {mod}", "", f"namespace {ns}", f"{opens} {rec_ns}", ""]
for k in pts:
    lines.append(f"set_option maxHeartbeats 0 in\ndef tcerts_{k} : CertMode := "
                 f"{certgen.table(certs.get((key, str(k)), []), (key, str(k)))}\n")
rows = ", ".join(f"({k}, tcerts_{k})" for k in pts)
lines += [f"def tableCerts : List (Nat × CertMode) := [{rows}]", "",
          "/-- The table with its certificates (no search in the kernel). -/",
          "def tablec : Table := { table with certs := tableCerts }", "", f"end {ns}", ""]
open(out, "w").write("\n".join(lines))
print(f"{len(pts)} points with certificates -> {out}", file=sys.stderr)
