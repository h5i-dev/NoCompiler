#!/usr/bin/env python3
"""The generated part of a copy or fill proof, for one function (docs/typed/value-tracker.md,
"The next copy"): from the linked record (`corpus.py --link --keep` output) to the kernel module of
its table check.

  1. `Examples/Musl/<Mod>Record.lean`: the record without its #eval tail;
  2. the producer (`scripts/tablegen.lean` with its Configuration block set) -> `<Mod>Table.lean`;
  3. `scripts/tabcerts.py` -> `<Mod>Certs.lean` (the tracker's certificates, `tablec`);
  4. `scripts/tabsplit.py` -> `<Mod>TabOk.lean` (`tab_ok`, one kernel check per point).

All outputs are untrusted hints: `tabOk` re-checks them in the kernel. Builds run under
`systemd-run -p MemoryMax=$TRACKGEN_MEM` (default 3G); the kernel module is written, not built.

Usage: lean/scripts/trackgen.py RECORD.lean FN MOD --regs DR,SR,NR --vars DV,SV,NV --width W
         [--fill] [--cursor R1,R2,...]
  e.g. trackgen.py nc-briefs/typed/musl-linked/wmemset.lean wmemset Wmemset \
         --regs 10,11,12 --vars 0,0,1 --width 4 --fill --cursor 13,14,10
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEAN = os.path.dirname(HERE)


def run(cmd, out=None, timeout=1800):
    mem = os.environ.get("TRACKGEN_MEM", "3G")
    pre = ["systemd-run", "--user", "--scope", "--quiet", "-p", f"MemoryMax={mem}",
           "-p", "MemorySwapMax=0", f"--setenv=PATH={os.environ['PATH']}"]
    r = subprocess.run([*pre, "timeout", str(timeout), *cmd], cwd=LEAN, capture_output=True,
                       text=True)
    if out:
        open(out, "w").write(r.stdout + r.stderr)
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("record")
    ap.add_argument("fn")
    ap.add_argument("mod")
    ap.add_argument("--regs", required=True)
    ap.add_argument("--vars", required=True)
    ap.add_argument("--width", type=int, default=1)
    ap.add_argument("--fill", action="store_true")
    ap.add_argument("--cursor", default="13,16,10")
    a = ap.parse_args()
    fn, Mod = a.fn, a.mod
    dr, sr, nr = a.regs.split(",")
    dv, sv, nv = a.vars.split(",")
    fill = "true" if a.fill else "false"
    ex = os.path.join(LEAN, "Examples", "Musl")
    # 1. the record
    src = open(a.record, encoding="utf-8").read()
    i = src.find("\n#eval")
    open(os.path.join(ex, f"{Mod}Record.lean"), "w").write(src if i < 0 else src[: i + 1])
    size = int(re.search(rf"def fn_{fn} : Fn where[\s\S]*?size := (\d+)", src).group(1))
    r = run(["lake", "build", f"Examples.Musl.{Mod}Record"])
    if r.returncode:
        sys.exit("record build failed:\n" + (r.stdout + r.stderr)[-2000:])
    # 2. the producer with this function's Configuration
    t = open(os.path.join(HERE, "tablegen.lean"), encoding="utf-8").read()
    t = t.replace("import Examples.Musl.MemcpyRecord", f"import Examples.Musl.{Mod}Record")
    t = t.replace("NoCompiler.Typed.Export.memcpy", f"NoCompiler.Typed.Export.{fn}")
    t = re.sub(r"^def F : Fn := .*$", f"def F : Fn := fn_{fn}", t, flags=re.M)
    t = re.sub(r"^def PP : Params := .*$", f"def PP : Params := ⟨{dv}, {sv}, {nv}, {a.width}, {fill}⟩", t, flags=re.M)
    t = re.sub(r"^def CC : CopyArgs := .*$", f"def CC : CopyArgs := ⟨{dr}, {sr}, {nr}, PP⟩", t, flags=re.M)
    t = re.sub(r"^def cursorPref : List Reg := .*$", f"def cursorPref : List Reg := [{a.cursor}]", t, flags=re.M)
    tmp = os.path.join(HERE, f"tablegen_{fn}_tmp.lean")
    open(tmp, "w").write(t)
    r = run(["lake", "lean", tmp])
    os.unlink(tmp)
    out = (r.stdout + r.stderr).split("\n")
    fails = [l for l in out if l.startswith("FAIL")]
    if fails or not any(l.startswith("def frames") for l in out):
        sys.exit("producer failed:\n" + "\n".join(fails or out[-40:]))
    i = next(k for k, l in enumerate(out) if l.startswith("def frames"))
    body = "\n".join(out[i:]).rstrip()
    body = body.replace("NoCompiler.Typed.Track.", "").replace("NoCompiler.Typed.", "").replace("NoCompiler.", "")
    open(os.path.join(ex, f"{Mod}Table.lean"), "w").write(f"""-- Generated by lean/scripts/trackgen.py (untrusted; `tabOk` checks it). Do not edit.
import Examples.Musl.{Mod}Record
import NoCompiler.Typed.Sound.TrackStep

namespace NoCompiler.Examples.Musl.{Mod}Table
open NoCompiler NoCompiler.Typed NoCompiler.Typed.Track

{body}

def table : Table := {{ frames, hints, moves, fins }}
def args : CopyArgs := ⟨{dr}, {sr}, {nr}, ⟨{dv}, {sv}, {nv}, {a.width}, {fill}⟩⟩

end NoCompiler.Examples.Musl.{Mod}Table
""")
    r = run(["lake", "build", f"Examples.Musl.{Mod}Table"])
    if r.returncode:
        sys.exit("table build failed:\n" + (r.stdout + r.stderr)[-2000:])
    # 3. certificates
    ns = f"NoCompiler.Examples.Musl.{Mod}Table"
    r = subprocess.run([sys.executable, os.path.join(HERE, "tabcerts.py"), f"Examples.Musl.{Mod}Table",
                        ns, f"fn_{fn}", str(size), os.path.join(ex, f"{Mod}Certs.lean")],
                       cwd=LEAN, capture_output=True, text=True)
    if r.returncode:
        sys.exit("tabcerts failed:\n" + (r.stdout + r.stderr)[-2000:])
    print(r.stderr.strip())
    # 4. the per-point kernel module
    r = subprocess.run([sys.executable, os.path.join(HERE, "tabsplit.py"), ns, f"fn_{fn}", str(size),
                        f"Examples.Musl.{Mod}Certs,NoCompiler.Typed.Sound.TrackStep",
                        f"NoCompiler.Typed.Export.{fn}", "tablec"], cwd=LEAN, capture_output=True, text=True)
    open(os.path.join(ex, f"{Mod}TabOk.lean"), "w").write(r.stdout)
    print(f"wrote Examples/Musl/{Mod}{{Record,Table,Certs,TabOk}}.lean ({size} points)")


if __name__ == "__main__":
    main()
